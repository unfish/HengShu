#[test]
fn report_and_chart_artifacts_match_across_interpreter_vm_and_package() {
    let outcome = assert_three_paths_with_artifacts(
        REPORT_SOURCE,
        &[("月度.csv", MONTHLY_CSV.as_bytes())],
        &[
            "趋势.svg",
            "柱状.svg",
            "散点.svg",
            "直方.svg",
            "箱线.svg",
            "堆叠.svg",
            "瀑布.svg",
            "报告.html",
            "报告.xlsx",
            "报告.pdf",
            "明细.csv",
        ],
    );
    let output = outcome.output.join("\n");
    // 统一检验契约的字段必须在三条路径上都可见。
    assert!(
        output.contains("配对样本t检验"),
        "缺少统一的方法字段：{output}"
    );
    assert!(output.contains("Cohen's d"), "缺少效应量名称：{output}");
    assert!(
        output.contains("诊断行数： 6"),
        "回归影响诊断应逐观测输出：{output}"
    );
    assert!(
        output.contains("共线性行数： 1"),
        "单预测变量的共线性表应只有一行：{output}"
    );
}

/// 受限权限下三条路径必须给出同一个错误类别，而不是某条路径静默写出文件。
#[test]
fn csv_rejects_nested_cells_identically_on_all_three_paths() {
    const NESTED_SOURCE: &str = r#"引入 统计分析
引入 报告

定义 样本 为 统计分析 数组([1, 2, 3, 4, 5])
定义 区间 为 统计分析 均值置信区间(样本, 置信度 为 0.95)

定义 嵌套报告 为 报告 创建("嵌套", [
    {"标题": "区间", "类型": "表格", "内容": [{"方法": "t 区间", "区间": [区间 的 下限, 区间 的 上限]}]}
])
报告 导出(嵌套报告, "CSV", "嵌套.csv")
"#;
    let outcome = common::assert_three_paths_failure(NESTED_SOURCE);
    assert!(
        outcome.message().contains("CSV 无法无损表达"),
        "三条路径都应拒绝嵌套单元格：{}",
        outcome.message()
    );
}
